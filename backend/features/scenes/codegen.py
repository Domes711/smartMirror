"""Generate `MagicMirror/config/pages.js` + `config/modules.js` from the DB.

Both are per-Pi generated artefacts (gitignored) and both are `require()`d by
the core. That is what lets SQLite be the single source of truth for module
instances without the core needing a database driver: the DB stays on the
Python side, and the core reads two plain JS files.

This is the one place in the backend that writes into the MagicMirror tree.
`config.js` is no longer touched — module instances live in the DB, not in a
marked block inside a hand-maintained file.
"""

import json
import logging
import os
import re

from shared import paths

log = logging.getLogger("scenes.codegen")

_GEN_HEADER = ("/* AUTO-GENERATED by the scenes feature — DO NOT EDIT BY HAND.\n"
               "   Manage layouts in the app (Scény). */\n")


# Reserved top-level keys in pages.js — a profile must never shadow them.
_RESERVED = ("globalLayout", "defaults")


def module_config(mtype: str, values: dict) -> dict:
    """Build a MagicMirror module `config` from the catalog field values.

    Most modules take the field values flat; these few need the values nested
    into the shape their own config expects.
    """
    v = values or {}
    if mtype == "MMM-GoogleCalendar":
        return {"calendars": [{"symbol": "calendar-week",
                               "calendarID": v.get("calendarID", "")}]}
    if mtype == "newsfeed":
        return {"feeds": [{"title": v.get("title") or "News",
                           "url": v.get("url", "")}]}
    if mtype == "weather":
        return {"weatherProvider": "openmeteo", "type": "current",
                "lat": v.get("lat"), "lon": v.get("lon"),
                "apiKey": v.get("apiKey")}
    if mtype == "MMM-Brno-Transit":
        cfg = {"stopName": v.get("stopName", "")}
        # IDS JMK GTFS feed (data.brno.cz dataset) — stable ArcGIS Hub
        # download; baked in so a stop picked on the map works without asking
        # the user for a URL.
        cfg["gtfsUrl"] = v.get("gtfsUrl") or \
            "https://www.arcgis.com/sharing/rest/content/items/379d2e9a7907460c8ca7fda1f3e84328/data"
        if v.get("stopId"):
            cfg["stopId"] = v["stopId"]
        return cfg
    if mtype in ("clock", "compliments"):
        return {}
    return dict(v)


def pages_object(store: dict) -> dict:
    out = {"defaults": store.get("defaults") or {}}
    for profile, wins in (store.get("windows") or {}).items():
        if profile in _RESERVED:
            continue
        out[profile] = {
            name: {"from": w["from"], "to": w["to"],
                   "layout": w.get("layout") or []}
            for name, w in (wins or {}).items()
        }
    return out


def managed_modules(store: dict, catalog_by_type: dict) -> list:
    """The `{id, module, placement, config}` objects written to modules.js.

    No `position` — placement into a region is driven solely by pages.js (see
    CLAUDE.md, "Module-management contract"); `placement` only says *whether*
    the profile system positions the module at all (`region`) or it renders
    through its own mechanism, like `alert` (`overlay`).
    """
    out = []
    for inst in store.get("instances") or []:
        cat = catalog_by_type.get(inst.get("type")) or {}
        # `config_json` is materialised at save time; fall back to deriving it
        # so a row written before that existed still produces a usable config.
        cfg = inst.get("config")
        if not cfg:
            cfg = module_config(inst.get("type"), inst.get("values"))
        out.append({
            "id": inst["id"],
            "module": cat.get("module") or inst.get("type"),
            "placement": inst.get("placement") or "region",
            "config": cfg,
        })
    return out


def previous_module_ids() -> set:
    """Ids in the currently generated modules.js.

    `apply_layout` compares this against the new set to decide whether the
    mirror can just reload pages.js (nothing new to load) or a module has to
    be hot-loaded into the running core.
    """
    if not os.path.isfile(paths.MODULES_JS_PATH):
        return set()
    try:
        with open(paths.MODULES_JS_PATH) as f:
            text = f.read()
    except Exception:  # noqa: BLE001
        return set()
    return set(re.findall(r'"id"\s*:\s*"([^"]+)"', text))


def generate(store: dict, catalog_by_type: dict) -> None:
    """Write `config/pages.js` (the layout schedule) and `config/modules.js`
    (the module instances) from the DB.

    Both are generated artefacts and both are `require()`d by the core, which
    is why the DB can be the single source of truth without the core needing
    a database driver: SQLite stays on the Python side, and the core reads two
    plain JS files it already knows how to load.
    """
    os.makedirs(os.path.dirname(paths.PAGES_PATH), exist_ok=True)

    pages_js = (_GEN_HEADER + "module.exports = " +
                json.dumps(pages_object(store), indent=4, ensure_ascii=False) +
                ";\n")
    with open(paths.PAGES_PATH, "w") as f:
        f.write(pages_js)

    modules_js = (_GEN_HEADER + "module.exports = " +
                  json.dumps(managed_modules(store, catalog_by_type),
                             indent=4, ensure_ascii=False) + ";\n")
    with open(paths.MODULES_JS_PATH, "w") as f:
        f.write(modules_js)

    log.info("generated pages.js + modules.js")
